    assert body["schema"] == "insight_import.v1"
    assert body["deduplicated"] is False
    record = body["insight"]
    assert record["schema"] == "insight_version.v1"
    assert record["insight_id"] == "insight-007"
    assert record["origin"] == "workshop"
    assert record["version"] == 1
    assert record["title"] == "開市頭30分鐘假突破多"
    assert record["instrument"] == "NQ"
    assert record["asset_class"] == "equity_index_futures"
    assert record["tag"] == "entry_within_open_30m"
    assert record["validation_status"] == "unverified"
    assert record["based_on_sketch"] == "sketch-20260725-02"
    assert record["based_on_sketch_origin"] == "workshop"
    assert record["imported_from_origin"] is None
    assert record["source_text"] == INSIGHT_YAML
    assert record["imported_at"].endswith("Z")

    stored = store.root / "workshop" / "insight-007" / "v1.yaml"
    assert stored.is_file()
    payload = yaml.safe_load(stored.read_text(encoding="utf-8"))
    assert payload["source_text"] == INSIGHT_YAML

    assert listed.status_code == 200
    listing = listed.json()
    assert listing["schema"] == "insight_list.v1"
    assert listing["count"] == 1
    summary = listing["insights"][0]
    assert summary["versions"] == [1]
    assert summary["latest_version"] == 1
    assert "source_text" not in summary

    assert detail.status_code == 200
    detail_body = detail.json()
    assert detail_body["schema"] == "insight_detail.v1"
    assert detail_body["version_count"] == 1
    assert detail_body["versions"][0]["source_text"] == INSIGHT_YAML


