def _replace(source: str, old: str, new: str) -> str:
    """Fail loudly instead of silently producing an unchanged fixture."""
    if old not in source:
        msg = f"fixture does not contain {old!r}"
        raise AssertionError(msg)
    return source.replace(old, new)


def _drop_line(source: str, needle: str) -> str:
    kept = [line for line in source.splitlines(keepends=True) if needle not in line]
    if len(kept) == len(source.splitlines(keepends=True)):
        msg = f"fixture does not contain a line with {needle!r}"
        raise AssertionError(msg)
    return "".join(kept)


def _store(tmp_path: Path, *, with_sketch: bool = False, **sketch_fields: str) -> InsightStore:
    sketch_root = tmp_path / "sketches"
    sketch_root.mkdir(parents=True, exist_ok=True)
    if with_sketch:
        _write_sketch(sketch_root, **sketch_fields)
    return InsightStore(
        root=tmp_path / "insights",
        sketch_store=SketchStore(root=sketch_root),
    )


def _write_sketch(
    sketch_root: Path,
    *,
    instrument: str = "NQ",
    asset_class: str = "equity_index_futures",
) -> Path:
    meta = _replace(SKETCH_META, "instrument: NQ", f"instrument: {instrument}")
    meta = _replace(
        meta,
        "asset_class: equity_index_futures",
        f"asset_class: {asset_class}",
    )
    folder = sketch_root / "workshop" / "sketch-20260725-02"
    folder.mkdir(parents=True)
    (folder / "meta.yaml").write_text(meta, encoding="utf-8")
    (folder / "INSTRUCTIONS.md").write_text(SKETCH_INSTRUCTIONS, encoding="utf-8")
    for filename in CHART_FILES:
        (folder / filename).write_bytes(PNG_SIGNATURE + filename.encode("utf-8"))
    return folder


@contextmanager
def _api_dependency(store: InsightStore) -> Iterator[None]:
    """Install a temp production store and restore any prior app state."""
    missing = object()
    prior = getattr(app.state, "insight_store", missing)
    app.state.insight_store = store
    try:
        yield
    finally:
        if prior is missing:
            delattr(app.state, "insight_store")
        else:
            app.state.insight_store = prior


def _file_inventory(root: Path) -> dict[str, bytes]:
    if not root.exists():
        return {}
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def _directory_inventory(root: Path) -> list[str]:
    if not root.exists():
        return []
    return sorted(
        path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_dir()
    )


@contextmanager
def _client() -> Iterator[httpx.AsyncClient]:
    transport = httpx.ASGITransport(app=app)
    yield httpx.AsyncClient(transport=transport, base_url="http://test")


async def _import(client: httpx.AsyncClient, source_text: str) -> httpx.Response:
    return await client.post(
        "/api/v1/insights/import",
        json={"source_text": source_text},
    )


